export interface Chat {
  /** Стабильный локальный ключ чата (номер телефона или chatId из MAX). */
  id: string
  /** Номер телефона собеседника (только цифры), если известен. */
  phone?: string
  /**
   * Куда отправлять сообщения. Изначально `79991234567@c.us`; после первого
   * входящего от собеседника заменяется на числовой chatId MAX.
   */
  chatId: string
  name?: string
  createdAt: number
}
